#!/usr/bin/env bash
# Stand up brain-go beside the harness and seed it for a benchmark run.
#
# The driver reaches brain-go at BRAIN_API_URL (default http://localhost:8001),
# so brain-go runs on this box rather than somewhere central.
#
# Two credentials, for two different things, because they are not
# interchangeable:
#
#   DEV_API_KEY   cli_{32hex}_{32hex}      -> the driver's /cli/chat bearer token
#   DEV_SESSION   session_{32hex}_{30hex}  -> creating the MCP connections
#
# A CLI API key carries no permissions at all: authz.go's APIServicePermissions
# returns nil for APIKeyTypeCLI, so it cannot POST /connections. The seeded user
# is UserRoleOwner, which has connections:create, so the session does that half.
# deploy/.env.sample says the same thing in its own comment.
#
# Both are generated by scripts/dev-env.sh into deploy/.env, and the compose
# stack's one-shot `seed` service (brainctl seed dev-stack) hashes them into the
# database during `make up`. No signup, no magic link, no impersonation header:
# signup returns "Check your email for login link" and local email delivery is a
# silent no-op, so there is no token to scrape.
#
# Called by the Terraform bootstrap (terraform/templates/bootstrap.sh.tftpl).
# Tracked by NOFireAI/brain-go#2219.

set -euo pipefail

BRAIN_GO_DIR="${BRAIN_GO_DIR:-/opt/brain-go}"
BRAIN_API_URL="${BRAIN_API_URL:-http://127.0.0.1:8000}"
BRAIN_CHAT_URL="${BRAIN_CHAT_URL:-http://127.0.0.1:8001}"
CUSTOMER="${BRAIN_GO_CUSTOMER:-sregym-bench}"
READY_TIMEOUT="${BRAIN_GO_READY_TIMEOUT:-600}"
ENV_OUT="${BRAIN_GO_ENV_OUT:-/etc/profile.d/sregym-brain-go.sh}"

log() { echo "[setup-brain-go] $*"; }
die() { echo "[setup-brain-go] ERROR: $*" >&2; exit 1; }

# Set a key in deploy/.env, replacing it if present and appending if not.
# dev-env.sh's set_key only fills keys that are empty, so it will not correct a
# key that already holds the wrong value; this will.
#
# Delete-then-append rather than a sed substitution. sed's replacement text
# treats & as "the whole match" and \ as an escape, so a value containing
# either rewrote the line into something else and still reported success:
# CHAT_SERVICE_TURN_TIMEOUT=a&b produced
# CHAT_SERVICE_TURN_TIMEOUT=aCHAT_SERVICE_TURN_TIMEOUT=900sb. Escaping the
# value would work but leaves the next caller to rediscover which characters
# need it; not putting the value in front of sed at all removes the class.
#
# The value now only ever reaches printf, which is why printf rather than echo:
# echo interprets backslash escapes in some shells. Only the key reaches sed,
# as a pattern, and callers constrain it to a shell name.
#
# The rewritten key moves to the end of the file. .env is unordered key=value
# pairs, so this changes nothing about what is read.
set_env_key() {
  local key="$1" value="$2"
  if grep -q "^${key}=" deploy/.env; then
    sed -i.bak "/^${key}=/d" deploy/.env && rm -f deploy/.env.bak
  fi

  printf '%s=%s\n' "$key" "$value" >>deploy/.env
}

# Resolved before the cd below, while $0 is still relative to the caller's
# working directory. After the cd a relative $0 would resolve inside the
# brain-go checkout, which has no scripts/benchmark.
SREGYM_SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

[ -d "$BRAIN_GO_DIR" ] || die "brain-go checkout not found at $BRAIN_GO_DIR"
cd "$BRAIN_GO_DIR"

# --- select the LLM provider before anything reads it ------------------------
# This has to happen before dev-env.sh runs, not after. dev-env.sh requires an
# Anthropic credential and exits 1 without one, and the only thing that waives
# that requirement is LLM_PROVIDER resolving to "bedrock". It resolves it from
# THIS environment variable: set_key_force writes the exported value into
# deploy/.env, then it reads the value back out of the file and gates on it
# (scripts/dev-env.sh). Writing LLM_PROVIDER into deploy/.env afterwards is too
# late, because the gate has already run and taken the process with it. That is
# what killed the first EC2 fleet: "dev-env: set ANTHROPIC_AUTH_TOKEN or
# ANTHROPIC_API_KEY (env var or deploy/.env) and re-run" on a box that was
# always meant to use Bedrock and has no Anthropic credential to give.
#
# This fleet has no first-party Anthropic key at all, only the instance role's
# Bedrock access (the Bedrock statement on sregym-benchmark-instance-role).
AGENT_MODEL_ID="${AGENT_MODEL_ID:?AGENT_MODEL_ID must be set; brain-go has no other source for which model to answer with}"
export LLM_PROVIDER=bedrock

# --- pin the tenant and the feature flags before the stack starts -------------
# A distinct customer gives a distinct account, which is what keeps concurrent
# runs from sharing a tenant.
./scripts/dev-env.sh ensure
set_env_key DEV_CUSTOMER "${CUSTOMER}"
log "tenant: $CUSTOMER"

# dev-env.sh has already written LLM_PROVIDER from the export above; these two
# have no such path and are set here. Kept alongside a redundant LLM_PROVIDER
# write so the file's provider config is stated in one place rather than
# depending on dev-env.sh's adoption behaviour staying as it is.
set_env_key LLM_PROVIDER bedrock
set_env_key LLM_MODEL "${AGENT_MODEL_ID}"
set_env_key BEDROCK_REGION "${AWS_DEFAULT_REGION:-us-east-1}"
log "answering model: $AGENT_MODEL_ID (bedrock, region ${AWS_DEFAULT_REGION:-us-east-1})"

# Force every cli_mode turn onto the RCI path (NOFireAI/brain-go#1547, merged as
# #1698). The flag is opt-in and off by default, so merging it was not enough:
# without this the supervisor's createPlan decides per turn whether to
# investigate, and it can return an empty plan that routes to FINISH or a
# guidance plan instead. A benchmark cannot tell that apart from a bad
# diagnosis, and the token counts the first run exists to capture would be
# measuring a conversational answer rather than an investigation.
#
# Both readers pick this up from deploy/.env: chatsvc for the in-process bridge
# and tworker for the Temporal path, since both compose services inherit
# env_file: .env.
set_env_key FEATURE_FORCE_RCI_FOR_CLI_ENABLED "${BRAIN_FORCE_RCI:-true}"
log "force-RCI for CLI turns: ${BRAIN_FORCE_RCI:-true}"

# Run the api and edge services at debug. brain-go writes its edge ingest
# success line, "ingested edge resource graph" with the account, connection,
# cluster, node and edge counts, whether the graph changed and whether the
# post created the connection, at DEBUG. At info the archived
# sregym-brain-go.log has no edge line at all, and a run cannot tell "no
# publish arrived" from "a publish arrived and was dropped" without reading
# the store code. At debug every edge publish that landed is in that log.
#
# This is the benchmark box only. brain-go's default and production level is
# info, and nothing here changes that. Do not lower this back to info to match
# production: the line it exists for would disappear.
#
# LOG_LEVEL is read by cmd/brain's process logger, which api and edge log
# through; chat, mcp and tworker build their own and ignore it. A brain-go
# checkout older than the LOG_LEVEL setting ignores the key and logs at info.
# No ordering constraint against dev-env.sh: it only needs to be in
# deploy/.env before `make up`. Written before BRAIN_ENV_EXTRA so a run can
# still override it.
set_env_key LOG_LEVEL debug
log "brain-go process log level: debug"

# --- reaching the api from inside a slot's kind cluster ----------------------
# The native arm's edge agent runs inside the slot's kind cluster and POSTs its
# resource graph to brain-go's /api/edge, so the api service has to be
# reachable from a container that is not on this host's loopback. It already
# is, on every box and in both arms: brain-go's own scripts/dev-env.sh writes
# BIND_ADDR=0.0.0.0 into deploy/.env whenever it creates that file, and the
# compose stack publishes every service on that address. Nothing here needs to
# arrange it.
#
# An earlier version of this script published the api a second time on the
# private address, through a compose override, on the theory that BIND_ADDR
# was still the sample's 127.0.0.1 and that widening it would expose postgres
# and localstack as well. Both halves were wrong. dev-env.sh had already set
# 0.0.0.0, so the stack was open either way and the override only added a
# duplicate binding: compose merges a service's ports with the base file's
# rather than replacing them, and the api container then failed to start with
# "address already in use". That is what stopped the first two native smokes,
# run-20260925-0705 and run-20260925-0803.
#
# The blast radius the override was avoiding is real and belongs to brain-go,
# not to this arm: dev-env.sh opens the whole stack, including the database,
# on every benchmark box today. terraform/network.tf has no inbound rule at
# all, so nothing outside the instance reaches those ports. Narrowing it is a
# change to brain-go's dev tooling, not something to work around here.

# --- run-configured knobs ----------------------------------------------------
# BRAIN_ENV_EXTRA carries KEY=VALUE lines from the run's terraform config
# (local.brain_env), so brain-go's tuning knobs can be swept per run instead of
# by editing this script (NOFireAI/brain-go#2282). It always carries at least
# CHAT_SERVICE_TURN_TIMEOUT, derived from the harness budget, because brain-go's
# own 15-minute default would truncate diagnoses and score them zero.
#
# Applied here, before the stack starts. docker compose reads .env at container
# start, so a value written after `make up` would not reach the process.
#
# Only key names are logged. These are tuning knobs today, but the mechanism is
# generic and a secret passed through it must not end up in a log that ships to
# S3.
if [ -n "${BRAIN_ENV_EXTRA:-}" ]; then
  applied=""
  while IFS= read -r entry; do
    case "$entry" in
      "" | \#*) continue ;;
    esac

    key="${entry%%=*}"
    value="${entry#*=}"

    # Entries are applied as they are read, so a malformed one partway down the
    # list dies with the entries above it already written. The instance
    # terminates on any die here, so a half-applied .env never starts a stack,
    # and terraform's own validation rejects both malformed shapes at plan.
    [ "$key" = "$entry" ] && die "BRAIN_ENV_EXTRA entry has no '=': $entry"

    # The key reaches sed as a pattern and has to be a valid .env name, so it is
    # constrained here. The value is not: set_env_key never puts it in front of
    # sed, so no character in it needs rejecting.
    case "$key" in
      *[!A-Za-z0-9_]* | [0-9]*) die "BRAIN_ENV_EXTRA key is not a shell name: $key" ;;
    esac

    set_env_key "$key" "$value"
    applied="$applied $key"
  done <<BRAIN_ENV_EOF
$BRAIN_ENV_EXTRA
BRAIN_ENV_EOF

  # Logged as one line so the applied configuration is recoverable from the
  # bootstrap log after the instance self-terminates.
  log "run-configured keys:${applied:- none}"
fi

# --- AWS credentials for the containers --------------------------------------
# Without these every LLM call fails and the agent submits nothing:
#
#   node "hypothesis_gen_agent": llm: bedrock converse: 403
#   UnrecognizedClientException: The security token included in the request is
#   invalid
#
# deploy/docker-compose.yml falls back to AWS_ACCESS_KEY_ID=test and
# AWS_SECRET_ACCESS_KEY=test unless the env file supplies real ones. Those are
# LocalStack placeholders, and that file's own comment says a real pair is
# expected to reach real AWS for everything except S3 and Secrets Manager.
# Bedrock is one of those everything-elses, so it got the placeholders.
#
# AWS_SESSION_TOKEN is not named in that compose file at all, so it reaches the
# containers purely through env_file: .env on x-app-common. It is required:
# instance-role credentials are always temporary, and a key and secret without
# the session token fail in exactly the same way.
#
# Read from IMDS on the host, not from inside a container. The metadata hop
# limit stays at 1, so nothing in a container can reach the endpoint and lift
# the instance role for itself. That matters here, where brain-go is driven by
# a model reading logs and metrics out of a deliberately broken application,
# and the instance role can read the SSM parameter holding the clone token.
#
# These expire. Instance-role credentials last about six hours and this is a
# snapshot that never refreshes, so a longer run will start failing LLM calls
# again. Acceptable under the current runtime cap; wants a refresh loop before
# any longer sweep.
IMDS_TOKEN=$(curl -sf -X PUT http://169.254.169.254/latest/api/token \
  -H 'X-aws-ec2-metadata-token-ttl-seconds: 300' 2>/dev/null || true)
IMDS_ROLE=""
if [ -n "$IMDS_TOKEN" ]; then
  IMDS_ROLE=$(curl -sf -H "X-aws-ec2-metadata-token: $IMDS_TOKEN" \
    http://169.254.169.254/latest/meta-data/iam/security-credentials/ 2>/dev/null | head -1 || true)
fi

if [ -n "$IMDS_ROLE" ]; then
  IMDS_CREDS=$(curl -sf -H "X-aws-ec2-metadata-token: $IMDS_TOKEN" \
    "http://169.254.169.254/latest/meta-data/iam/security-credentials/$IMDS_ROLE" 2>/dev/null || true)
  AWS_KEY=$(printf '%s' "$IMDS_CREDS" | jq -r '.AccessKeyId // empty')
  AWS_SECRET=$(printf '%s' "$IMDS_CREDS" | jq -r '.SecretAccessKey // empty')
  AWS_TOKEN=$(printf '%s' "$IMDS_CREDS" | jq -r '.Token // empty')

  [ -n "$AWS_KEY" ] && [ -n "$AWS_SECRET" ] && [ -n "$AWS_TOKEN" ] \
    || die "IMDS returned incomplete credentials for role $IMDS_ROLE; every Bedrock call would 403"

  set_env_key AWS_ACCESS_KEY_ID "$AWS_KEY"
  set_env_key AWS_SECRET_ACCESS_KEY "$AWS_SECRET"
  set_env_key AWS_SESSION_TOKEN "$AWS_TOKEN"
  log "instance-role credentials written for $IMDS_ROLE, expiring $(printf '%s' "$IMDS_CREDS" | jq -r '.Expiration // "unknown"')"
else
  # Not fatal: on a developer box there is no instance role, and whatever
  # credentials deploy/.env or the caller's environment already provides are
  # the right ones. Said loudly because on an instance it means every LLM call
  # is about to 403.
  log "WARNING: no instance role via IMDS; leaving whatever credentials deploy/.env already has"
fi

# --- bring up the stack ------------------------------------------------------
# Temporal is not optional. buildWorkflowChat is called unconditionally in
# chatsvc/wiring.go and errors if the Temporal client cannot be built, so the
# chat service will not start without it. It is also what routes cli_mode turns
# onto the RCI path rather than the in-process bridge.
#
# `make up` runs dev-env.sh ensure, builds, and starts everything including the
# one-shot seed service, which is what actually creates the tenant.
log "bringing up the dev stack (postgres, temporal, tworker, api, chat, mcp, edge, seed)"
make up

# --- wait for readiness ------------------------------------------------------
log "waiting for brain-go (timeout ${READY_TIMEOUT}s)"
deadline=$(( $(date +%s) + READY_TIMEOUT ))
for url in "${BRAIN_API_URL}/health" "${BRAIN_CHAT_URL}/health"; do
  until curl -sf "$url" >/dev/null 2>&1; do
    [ "$(date +%s)" -lt "$deadline" ] || die "not ready within ${READY_TIMEOUT}s: $url"
    sleep 3
  done
  log "ready: $url"
done

# --- read back what the seed hashed into the database ------------------------
# shellcheck disable=SC1091
DEV_API_KEY=$(grep '^DEV_API_KEY=' deploy/.env | cut -d= -f2-)
DEV_SESSION=$(grep '^DEV_SESSION=' deploy/.env | cut -d= -f2-)
[ -n "$DEV_API_KEY" ] || die "DEV_API_KEY is empty in deploy/.env; the seed cannot have run"
[ -n "$DEV_SESSION" ] || die "DEV_SESSION is empty in deploy/.env; connections cannot be created"

# The seed service is one-shot and does not block `make up`, so confirm it
# actually finished rather than assuming. An unmatched key means a previous run
# seeded a different token under the same name and EnsureAPIKey's
# ON CONFLICT DO NOTHING left the old hash in place.
if ! docker compose --env-file deploy/.env logs seed 2>/dev/null | grep -q "Dev stack ready"; then
  log "seed did not report success, re-running it"
  docker compose --env-file deploy/.env up --exit-code-from seed seed \
    || die "brainctl seed dev-stack failed"
fi

# --- hand the driver what it needs -------------------------------------------
# The URL only. Connections are not registered here any more, and no per-slot
# API key is minted here either.
#
# Registering them means discovering each endpoint's tool schemas from a live
# SREGym MCP server, because brain-go never populates tools_cache itself (see
# seed_connections.py). That server is deployed by the conductor's deploy_app(),
# which runs per problem from start_problem(), so on a fresh cluster it does not
# exist yet. This script used to wait 300s for it and then die:
#
#   [setup-brain-go] waiting for the SREGym MCP server at http://10.0.0.1:9954
#   [setup-brain-go] ERROR: SREGym MCP server not reachable
#
# It only ever appeared to work on a developer box, where an earlier run had
# left the server deployed and its port-forward alive.
#
# Seeding now happens per slot, after that slot's cluster exists and
# deploy_mcp.py has put a server in it. Every slot calls seed_slot.sh, slot 0
# included, which also removes slot 0's special case -- the only reason this
# script ever needed to know about MCP ports.
#
# No BRAIN_SSE_READ_TIMEOUT override: brain-go now sends an SSE keepalive
# every 15s (NOFireAI/brain-go#2250), so the driver's own default is already
# tuned for that and needs no deployment-level override.
install -m 0600 /dev/null "$ENV_OUT"
cat >"$ENV_OUT" <<ENVEOF
export BRAIN_API_URL="${BRAIN_CHAT_URL}"
ENVEOF

log "stack ready. BRAIN_API_URL=$BRAIN_CHAT_URL, written to $ENV_OUT"
log "connections are seeded per slot, once each slot's cluster is up"
