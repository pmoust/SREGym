#!/usr/bin/env bash
# Stand up brain-go beside the harness and seed it for a benchmark run.
#
# The driver reaches brain-go at BRAIN_API_URL (default http://localhost:8001),
# so brain-go runs on this box rather than somewhere central.
#
# Two credentials, for two different things, because they are not
# interchangeable:
#
#   DEV_API_KEY   cli_{32hex}_{32hex}      -> the driver's /cli/chat bearer token
#   DEV_SESSION   session_{32hex}_{30hex}  -> creating the MCP connections
#
# A CLI API key carries no permissions at all: authz.go's APIServicePermissions
# returns nil for APIKeyTypeCLI, so it cannot POST /connections. The seeded user
# is UserRoleOwner, which has connections:create, so the session does that half.
# deploy/.env.sample says the same thing in its own comment.
#
# Both are generated by scripts/dev-env.sh into deploy/.env, and the compose
# stack's one-shot `seed` service (brainctl seed dev-stack) hashes them into the
# database during `make up`. No signup, no magic link, no impersonation header:
# signup returns "Check your email for login link" and local email delivery is a
# silent no-op, so there is no token to scrape.
#
# Called by the Terraform bootstrap (terraform/templates/bootstrap.sh.tftpl).
# Tracked by NOFireAI/brain-go#2219.

set -euo pipefail

BRAIN_GO_DIR="${BRAIN_GO_DIR:-/opt/brain-go}"
BRAIN_API_URL="${BRAIN_API_URL:-http://127.0.0.1:8000}"
BRAIN_CHAT_URL="${BRAIN_CHAT_URL:-http://127.0.0.1:8001}"
CUSTOMER="${BRAIN_GO_CUSTOMER:-sregym-bench}"
MCP_PORT="${SREGYM_MCP_PORT:-9954}"
READY_TIMEOUT="${BRAIN_GO_READY_TIMEOUT:-600}"
ENV_OUT="${BRAIN_GO_ENV_OUT:-/etc/profile.d/sregym-brain-go.sh}"

log() { echo "[setup-brain-go] $*"; }
die() { echo "[setup-brain-go] ERROR: $*" >&2; exit 1; }

[ -d "$BRAIN_GO_DIR" ] || die "brain-go checkout not found at $BRAIN_GO_DIR"
cd "$BRAIN_GO_DIR"

# --- the private address the MCP connections must use ------------------------
# brain-go's SSRF guard blocks loopback outright. allow_private_endpoint lifts
# RFC1918 and ULA only, and no flag lifts loopback. brain-go also dials from
# inside a container, where localhost is the container's own loopback, so the
# host's private address is required on both counts.
PRIVATE_IP="${SREGYM_PRIVATE_IP:-$(ip -4 -o addr show scope global 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -1)}"
[ -n "$PRIVATE_IP" ] || die "could not determine a private IPv4 address; set SREGYM_PRIVATE_IP"
case "$PRIVATE_IP" in
  10.*|192.168.*|172.1[6-9].*|172.2[0-9].*|172.3[0-1].*) ;;
  *) die "resolved '$PRIVATE_IP', which is not RFC1918; allow_private_endpoint would not cover it" ;;
esac
MCP_BASE="http://${PRIVATE_IP}:${MCP_PORT}"
log "private address $PRIVATE_IP, MCP base $MCP_BASE"

# --- pin the tenant name before anything generates .env ----------------------
# A distinct customer gives a distinct account, which is what keeps concurrent
# runs from sharing a tenant. dev-env.sh's set_key only fills empty keys, so
# writing this first survives its run.
./scripts/dev-env.sh ensure
if grep -q '^DEV_CUSTOMER=' deploy/.env; then
  sed -i.bak "s|^DEV_CUSTOMER=.*|DEV_CUSTOMER=${CUSTOMER}|" deploy/.env && rm -f deploy/.env.bak
else
  echo "DEV_CUSTOMER=${CUSTOMER}" >>deploy/.env
fi
log "tenant: $CUSTOMER"

# --- bring up the stack ------------------------------------------------------
# Temporal is not optional. buildWorkflowChat is called unconditionally in
# chatsvc/wiring.go and errors if the Temporal client cannot be built, so the
# chat service will not start without it. It is also what routes cli_mode turns
# onto the RCI path rather than the in-process bridge.
#
# `make up` runs dev-env.sh ensure, builds, and starts everything including the
# one-shot seed service, which is what actually creates the tenant.
log "bringing up the dev stack (postgres, temporal, tworker, api, chat, mcp, edge, seed)"
make up

# --- wait for readiness ------------------------------------------------------
log "waiting for brain-go (timeout ${READY_TIMEOUT}s)"
deadline=$(( $(date +%s) + READY_TIMEOUT ))
for url in "${BRAIN_API_URL}/health" "${BRAIN_CHAT_URL}/health"; do
  until curl -sf "$url" >/dev/null 2>&1; do
    [ "$(date +%s)" -lt "$deadline" ] || die "not ready within ${READY_TIMEOUT}s: $url"
    sleep 3
  done
  log "ready: $url"
done

# --- read back what the seed hashed into the database ------------------------
# shellcheck disable=SC1091
DEV_API_KEY=$(grep '^DEV_API_KEY=' deploy/.env | cut -d= -f2-)
DEV_SESSION=$(grep '^DEV_SESSION=' deploy/.env | cut -d= -f2-)
[ -n "$DEV_API_KEY" ] || die "DEV_API_KEY is empty in deploy/.env; the seed cannot have run"
[ -n "$DEV_SESSION" ] || die "DEV_SESSION is empty in deploy/.env; connections cannot be created"

# The seed service is one-shot and does not block `make up`, so confirm it
# actually finished rather than assuming. An unmatched key means a previous run
# seeded a different token under the same name and EnsureAPIKey's
# ON CONFLICT DO NOTHING left the old hash in place.
if ! docker compose --env-file deploy/.env logs seed 2>/dev/null | grep -q "Dev stack ready"; then
  log "seed did not report success, re-running it"
  docker compose --env-file deploy/.env up --exit-code-from seed seed \
    || die "brainctl seed dev-stack failed"
fi

# --- register the MCP connections --------------------------------------------
log "waiting for the SREGym MCP server at $MCP_BASE"
deadline=$(( $(date +%s) + 300 ))
until curl -s -o /dev/null --max-time 3 "${MCP_BASE}/kubectl/sse" 2>/dev/null; do
  [ "$(date +%s)" -lt "$deadline" ] || die "SREGym MCP server not reachable at $MCP_BASE"
  sleep 5
done

log "registering four CUSTOM_MCP connections"
uv run python "$(cd "$(dirname "$0")" && pwd)/seed_connections.py" \
  --brain-url "$BRAIN_API_URL" \
  --mcp-base "$MCP_BASE" \
  --session "$DEV_SESSION" \
  --session-id "sregym-${CUSTOMER}"

# --- hand the driver what it needs -------------------------------------------
# BRAIN_SSE_READ_TIMEOUT is raised from the driver's 120s default because
# brain-go sends no SSE keepalive (NOFireAI/brain-go#2249): a slow tool call or a
# long model turn is indistinguishable from a dead connection. The harness's own
# agent timeout is the real backstop. Drop this override once #2249 lands.
install -m 0600 /dev/null "$ENV_OUT"
cat >"$ENV_OUT" <<ENVEOF
export BRAIN_API_URL="${BRAIN_CHAT_URL}"
export BRAIN_API_KEY="${DEV_API_KEY}"
export BRAIN_SSE_READ_TIMEOUT="${BRAIN_SSE_READ_TIMEOUT:-900}"
ENVEOF

log "ready. BRAIN_API_URL=$BRAIN_CHAT_URL, credentials in $ENV_OUT"
