#!/usr/bin/env python3
"""Write the conductor's tasklist for the problems this shard owns.

The conductor reads sregym/conductor/tasklist.yml to decide which stages it
grades for a problem (Conductor.get_problem_stages). A problem the file does
not list falls back to both diagnosis and mitigation, and says so only in a
log line nobody reads. So the file has to be derived from the exact list the
shard runs rather than written by hand: a hand-written file that misses one
problem runs that problem's mitigation turn at full cost and reads as a
normal run afterwards.

Inputs come from the environment, not argv, for the reason run_shard.sh gives
where it resolves PROBLEMS: a value spliced into a command line is one quote
away from being read as something else.

    TASKLIST_PATH   where to write the file
    PROBLEMS        space-separated problem ids, the shard's resolved list
    SREGYM_STAGES   "diagnosis" (default) or "diagnosis,mitigation"

Exits non-zero on a rejected SREGYM_STAGES, an empty problem list, a write
failure, or a readback whose problem set is not exactly PROBLEMS. The caller
terminates the run on any of those, because every one of them ends with the
conductor grading stages the run did not ask for.
"""

import os
import sys
from pathlib import Path

import yaml

# The conductor accepts any ordered subset of [diagnosis, mitigation]. Only
# these two are offered here: an empty tasklist raises in the conductor, and
# mitigation alone would grade a fix for a diagnosis that was never made.
ALLOWED = {
    "diagnosis": ["diagnosis"],
    "diagnosis,mitigation": ["diagnosis", "mitigation"],
}

HEADER = """# Generated by scripts/benchmark/write_tasklist.py at shard start.
# Lists every problem this shard runs, so none of them falls back to the
# conductor's both-stage default. Edits here do not survive the next shard.
"""


def main() -> int:
    spec = os.environ.get("SREGYM_STAGES", "diagnosis")
    if spec not in ALLOWED:
        sys.stderr.write(f"SREGYM_STAGES must be one of {sorted(ALLOWED)}, got: {spec!r}\n")

        return 2
    stages = ALLOWED[spec]

    problems = os.environ.get("PROBLEMS", "").split()
    if not problems:
        sys.stderr.write("PROBLEMS is empty, so there is no tasklist to write\n")

        return 2

    path = Path(os.environ.get("TASKLIST_PATH", ""))
    if not path.name:
        sys.stderr.write("TASKLIST_PATH is empty\n")

        return 2

    body = yaml.safe_dump(
        {"all": {"problems": {problem: list(stages) for problem in sorted(set(problems))}}},
        sort_keys=True,
        default_flow_style=False,
    )
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(HEADER + body)
    except OSError as exc:
        sys.stderr.write(f"could not write {path}: {exc}\n")

        return 1

    # Read it back rather than trust the write. The cost of a file that lists
    # the wrong problems is a run that grades stages nobody asked for and bills
    # for them, which no later step notices.
    try:
        written = (yaml.safe_load(path.read_text()) or {})["all"]["problems"]
    except (OSError, ValueError, KeyError, TypeError) as exc:
        sys.stderr.write(f"could not read back {path}: {exc}\n")

        return 1

    if set(written) != set(problems):
        missing = sorted(set(problems) - set(written))
        extra = sorted(set(written) - set(problems))
        sys.stderr.write(f"{path} does not match PROBLEMS: missing={missing} unexpected={extra}\n")

        return 1

    wrong = sorted(pid for pid, got in written.items() if got != stages)
    if wrong:
        sys.stderr.write(f"{path} has the wrong stages for: {wrong}\n")

        return 1

    print(f"[bootstrap] tasklist: {len(written)} problems, stages {spec} -> {path}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
